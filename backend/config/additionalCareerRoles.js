const SKILL_SOURCES = [
  "skills",
  "projects.technologies",
  "projects.description",
  "projects.highlights",
  "experience.title",
  "experience.highlights",
  "education.details",
  "certifications.name",
];
const PROJECT_SOURCES = [
  "projects.name",
  "projects.description",
  "projects.technologies",
  "projects.highlights",
];
const EXPERIENCE_SOURCES = ["experience.title", "experience.highlights"];
const EXPERIENCE_HIGHLIGHT_SOURCES = ["experience.highlights"];
const EDUCATION_SOURCES = [
  "education.degree",
  "education.fieldOfStudy",
  "education.details",
];
const CERTIFICATION_SOURCES = ["certifications.name", "certifications.issuer"];

const CATALOGUE_VERSION = "1.0.0";
const PROFILE_VERSION = "1.0.0";

function item(id, label, weight, aliases, prerequisites = []) {
  return { id, label, weight, aliases, prerequisites };
}

function criterion(roleId, definition, category, kind, sources) {
  return {
    id: `${roleId}-${definition.id}`,
    label: definition.label,
    category,
    kind,
    weight: definition.weight,
    aliases: definition.aliases,
    sources,
    prerequisiteCriterionIds: definition.prerequisites.map((prerequisiteId) => `${roleId}-${prerequisiteId}`),
  };
}

function createProfile(definition) {
  const { id } = definition;
  return {
    id,
    name: definition.title,
    title: definition.title,
    titleAliases: definition.aliases,
    description: definition.description,
    category: definition.category,
    profileVersion: PROFILE_VERSION,
    catalogueVersion: CATALOGUE_VERSION,
    scoringReady: true,
    featured: false,
    source: {
      name: "Pathwise curated catalogue",
      reference: "Reviewed against established occupational families and Pathwise evidence rules.",
    },
    relatedRoleIds: definition.relatedRoleIds,
    criteria: [
      ...definition.core.map((entry) => criterion(id, entry, "coreSkills", "skill", SKILL_SOURCES)),
      ...definition.supporting.map((entry) => criterion(id, entry, "supportingSkills", "skill", SKILL_SOURCES)),
      criterion(id, definition.project, "projectEvidence", "project", PROJECT_SOURCES),
      criterion(id, definition.projectTools, "projectEvidence", "project", PROJECT_SOURCES),
      criterion(id, definition.experience, "experienceEvidence", "experience", EXPERIENCE_SOURCES),
      criterion(id, definition.responsibilities, "experienceEvidence", "experience", EXPERIENCE_HIGHLIGHT_SOURCES),
      criterion(id, definition.education, "educationCertifications", "education", EDUCATION_SOURCES),
      criterion(id, definition.certification, "educationCertifications", "certification", CERTIFICATION_SOURCES),
    ],
  };
}

